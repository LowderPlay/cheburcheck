<KbArticle>
	<h1>Динамическое сканирование</h1>

	<p>
		Обычная проверка Cheburcheck отвечает на вопрос «есть ли домен, IP-адрес или
		подсеть в известных списках блокировок». Это полезно, но не всегда
		достаточно: часть ограничений не публикуется в открытых реестрах и зависит
		от того, как именно оператор связи обрабатывает конкретное соединение.
	</p>
	<p>
		Для таких случаев мы добавили динамическое сканирование. Оно не только
		сравнивает домен со списками, но и просит внешние динамические сканеры
		попробовать загрузить данные так, как это сделал бы пользователь из своей
		сети. Ответы сканеров приходят в реальном времени, поэтому результат может
		уточняться прямо на странице проверки.
	</p>

	<KbNote variant="info">
		Динамическое сканирование не заменяет основную проверку по спискам. Оно
		помогает понять, как домен ведет себя «вживую» у доступных сканеров.
	</KbNote>

	<KbHeading id="как-это-работает" title="Как это работает">
		Как это работает
	</KbHeading>
	<p>
		Когда вы запускаете динамическую проверку домена, сайт отправляет задачу
		доступным сканерам. Каждый сканер получает домен, выполняет несколько
		коротких проверок и отправляет ответ обратно. Страница показывает ответы
		сразу, не дожидаясь завершения всех проверок.
	</p>
	<p>
		Сканер не загружает целевой сайт целиком. Для домена он делает небольшие
		контрольные HTTPS-загрузки с тестовых хостов, подставляя проверяемое имя в
		SNI, а также сравнивает ответы нескольких публичных DNS-сервисов.
	</p>

	<KbHeading id="методика-сканирования" title="Методика сканирования">
		Методика сканирования
	</KbHeading>
	<p>
		Сканер подключается к настроенным тестовым хостам, но передаёт проверяемый
		домен в TLS ClientHello и HTTP Host. Затем он оценивает, удалось ли
		завершить TLS-обмен и получить минимальный объём данных. Для проверки
		IP-адреса без домена этот этап пропускается.
	</p>
	<ul class="list-disc">
		<li>
			При получении конфигурации сканер отдельно для IPv4 и IPv6 измеряет
			положение DPI в сети. Он подключается к контрольному серверу на порту 443,
			отправляет TLS ClientHello с контрольным SNI, а затем посылает TCP-пакеты
			с последовательно увеличивающимся TTL. Ответы ICMP Time Exceeded
			показывают, какие переходы пакет успел пройти. Результат сохраняется
			отдельно для каждой версии IP.
		</li>
		<li>
			При проверке целевого IP-адреса TCP-трассировка начинается со следующего
			после DPI перехода — <code>dpi_hop + 1</code>. По умолчанию проверяются
			три перехода, на каждом из которых одновременно выполняются три попытки.
			Первый ответ ICMP Time Exceeded, TCP RST или успешное соединение
			немедленно завершает трассировку.
		</li>
	</ul>
	<p>
		Если DPI был измерен, но ни одна попытка после него не получила ответа,
		сканер выставляет вердикт «ТСПУ Блок» и показывает измеренный переход DPI.
		Любой ответ после DPI означает, что пакеты прошли дальше, поэтому блокировка
		IP-адреса на ТСПУ не подтверждается. Если переход DPI для нужной версии IP
		не удалось определить, трассировка пропускается и этот вердикт не
		выставляется.
	</p>
	<KbNote variant="info">
		Измерение выполняется независимо для IPv4 и IPv6. Разрыв TCP-соединения во
		время калибровки делает результат этой версии IP недействительным, чтобы не
		принимать поведение контрольного сервера за работу DPI.
	</KbNote>

	<KbHeading id="проверка-dns" title="Проверка DNS"> Проверка DNS </KbHeading>
	<p>
		Для доменных имён сканер обращается к Google DNS, Cloudflare, Quad9 и Яндекс
		DNS. Запросы к каждому сервису выполняются параллельно по UDP, TCP, DNS over
		HTTPS (DoH) и DNS over TLS (DoT). Каждый вариант запускается несколько раз,
		чтобы обычная ротация адресов CDN и балансировщиков меньше влияла на
		результат.
	</p>
	<p>
		Сами IP-адреса могут законно отличаться между запросами, поэтому сканер не
		требует их точного совпадения. Для сравнения используется форма ответа: код
		DNS и количество уникальных IPv4- и IPv6-адресов. Ответы DoH и DoT одного
		провайдера служат зашифрованным ориентиром. UDP или TCP считается
		подозрительным, когда его форма отличается от совпавших между собой
		зашифрованных ответов.
	</p>
	<KbNote variant="info">
		Одиночное расхождение ещё не означает подмену. Итоговый вердикт появляется,
		только когда подозрительный результат независимо подтверждают несколько
		DNS-провайдеров — обычно не менее двух. Несколько протоколов одного
		провайдера считаются одним подтверждением.
	</KbNote>

	<KbHeading id="что-показывает-результат" title="Что показывает результат">
		Что показывает результат
	</KbHeading>
	<p>
		В динамическом результате есть общий вердикт и подробности по отдельным
		тестовым хостам. Общий вердикт — это краткое обобщение того, что увидел
		конкретный сканер.
	</p>
	<ul class="list-disc">
		<li>
			<b>Доступен</b>
			– сайт не найден в списках CDN, не блокируется на контрольных хостах, но
			может блокироваться на зарубежных CDN.
		</li>
		<li>
			<b>CDN Блок (16-20)</b>
			– сайт найден в списках CDN, не блокируется на контрольных хостах, но
			блокируется на зарубежных CDN.
		</li>
		<li>
			<b>SNI Блок</b>
			– похоже на блокировку по домену сайта в начале HTTPS-соединения. На
			практике это похоже на ситуацию, когда оборудование оператора (ТСПУ) видит
			имя домена и разрывает соединение до передачи полезных данных.
		</li>
		<li>
			<b>Подмена DNS</b>
			– открытые DNS-запросы по UDP или TCP у нескольких независимых провайдеров
			отличаются от их ответов по защищённым протоколам DoH и DoT. Если
			одновременно обнаружена SNI-блокировка, в общем вердикте приоритет
			получает
			<b>SNI Блок</b>.
		</li>
		<li>
			<b>ТСПУ Блок</b>
			– переход DPI был измерен, но короткая TCP-трассировка, начатая сразу
			после него, не получила ни ICMP-ответа, ни TCP RST и не смогла
			подключиться к цели. Это указывает на возможную блокировку IP-адреса на
			оборудовании оператора.
		</li>
		<li>
			<!-- biome-ignore format: link punctuation -->
			<a
				class="underline decoration-dotted underline-offset-2"
				href="/kb/whitelist"
			>Исключение для CDN</a> – данные передаются в полном объеме при
			подстановке домена в SNI при подключении к заблокированному серверу.
		</li>

		<li>
			<b>Неясно</b>
			– данных недостаточно или ответы противоречат друг другу.
		</li>
	</ul>

	<KbHeading id="подробности-по-хостам" title="Подробности по хостам">
		Подробности по хостам
	</KbHeading>
	<p>
		У каждого тестового хоста есть собственное наблюдение. Оно помогает понять,
		из чего сложился общий вердикт:
	</p>
	<ul class="list-disc">
		<li><b>Успешно</b> — сканер получил достаточно данных.</li>
		<li>
			<b>Таймаут получения данных</b>
			— соединение началось, но данных пришло меньше ожидаемого объёма.
		</li>
		<li>
			<b>Блокировка после ClientHello</b>
			— соединение оборвалось на раннем этапе HTTPS.
		</li>
		<li>
			<b>Ошибка подключения</b>
			— сканер не смог подключиться к тестовому хосту.
		</li>
	</ul>
	<p>
		Один сбойный хост сам по себе не доказывает блокировку. Важно смотреть на
		большинство ответов и на то, какие именно хосты дали сбой: контрольные,
		проверочные или все сразу.
	</p>
	<p>
		В раскрытой строке результата DNS-проверка показана отдельно от
		CDN-проверки. Для каждого DNS-провайдера видны UDP, TCP, DoH и DoT, код
		ответа, счётчик IPv4/IPv6 и оценка расхождения. Ошибка запроса означает лишь
		то, что конкретное измерение не удалось, и сама по себе не считается
		подменой.
	</p>

	<KbHeading
		id="почему-результаты-могут-отличаться"
		title="Почему результаты могут отличаться"
	>
		Почему результаты могут отличаться
	</KbHeading>
	<p>
		Блокировки могут отличаться у разных операторов, в разных регионах и даже в
		разное время суток. Динамический сканер показывает состояние из той сети,
		где он запущен. Поэтому несколько сканеров могут дать разные ответы — это не
		ошибка, а часть реальности таких блокировок.
	</p>
	<p>
		Также стоит учитывать временные проблемы: недоступность тестового хоста,
		перегрузку сети, потери пакетов или слишком медленное соединение. Поэтому
		динамический результат лучше воспринимать как сильный сигнал, а не как
		абсолютное юридическое или техническое доказательство.
	</p>
</KbArticle>
